// 6. Gemini Multi-Turn Chatbot (gemini-3.1-pro-preview / gemini-3.5-flash / gemini-3.1-flash-lite)
// -------------------------------------------------------------
app.post('/api/chat', async (req, res) => {
  try {
    const {
      messages = [],
      role = 'mentor',
      model = 'gemini-3.5-flash',
    } = req.body;

    let systemInstruction = '';
    switch (role) {
      case 'master_tobias':
        systemInstruction = `You are Master Tobias, the patient elderly horologist from "The Clockmaker of Whispering Pines". You speak in warm, gentle, contemplative prose. You relate every question to clockwork, craftsmanship, holding one's breath, and finding forgiveness in lost seconds. Never break character.`;
        break;
      case 'elena_vance':
        systemInstruction = `You are Elena Vance, the celebrated author and philosopher behind Mythos & Quill. You explain narrative structure, pedagogical themes for middle graders, why perfectionism binds children, and how to craft moral fables. Speak thoughtfully and encourage storytelling craft.`;
        break;
      case 'literary_scholar':
        systemInstruction = `You are an erudite literature professor and moral philosopher analyzing allegorical parables, historical motifs of time and mortality, and pedagogical storytelling methods. You provide deep, analytical, yet warmly inspiring reflections.`;
        break;
      default:
        systemInstruction = `You are the Socratic Story Mentor of Mythos & Quill. You help readers, educators, and seekers explore deep themes, answer philosophical sparks, and discover moral growth through thoughtful guided dialogue.`;
        break;
    }

    // Model selection validation
    let selectedModel = 'gemini-3.5-flash';
    if (model === 'gemini-3.1-pro-preview') {
      selectedModel = 'gemini-3.1-pro-preview';
    } else if (model === 'gemini-3.1-flash-lite') {
      selectedModel = 'gemini-3.1-flash-lite';
    }

    const ai = getGeminiClient();

    // Map messages format
    const formattedContents = messages.map((m: any) => ({
      role: m.sender === 'user' ? 'user' : 'model',
      parts: [{ text: m.text }],
    }));

    const response = await ai.models.generateContent({
      model: selectedModel,
      contents: formattedContents,
      config: {
        systemInstruction,
      },
    });

    res.json({
      text: response.text || '',
      modelUsed: selectedModel,
    });
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Chat generation failed');
    console.error('Chat error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

