// 1. Lyria Music Generation (lyria-3-clip-preview / lyria-3-pro-preview)
// -------------------------------------------------------------
app.post('/api/music/generate', async (req, res) => {
  try {
    const { prompt, model = 'lyria-3-clip-preview', imageBase64, mimeType = 'image/jpeg' } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const ai = getGeminiClient();

    let contents: any = prompt;
    if (imageBase64) {
      contents = {
        parts: [
          { text: prompt },
          { inlineData: { data: imageBase64, mimeType } }
        ]
      };
    }

    const response = await ai.models.generateContentStream({
      model: model === 'lyria-3-pro-preview' ? 'lyria-3-pro-preview' : 'lyria-3-clip-preview',
      contents,
    });

    let audioBase64 = '';
    let lyrics = '';
    let responseMimeType = 'audio/wav';

    for await (const chunk of response) {
      const parts = chunk.candidates?.[0]?.content?.parts;
      if (!parts) continue;
      for (const part of parts) {
        if (part.inlineData?.data) {
          if (!audioBase64 && part.inlineData.mimeType) {
            responseMimeType = part.inlineData.mimeType;
          }
          audioBase64 += part.inlineData.data;
        }
        if (part.text && !lyrics) {
          lyrics = part.text;
        }
      }
    }

    if (!audioBase64) {
      return res.status(500).json({ error: 'No audio generated by the model' });
    }

    res.json({
      audioBase64,
      mimeType: responseMimeType,
      lyrics,
      model,
    });
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Music generation failed');
    console.error('Music generation error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

