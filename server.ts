// 4. Video Generation & Image-to-Video with Veo (veo-3.1-fast-generate-preview)
// -------------------------------------------------------------
app.post('/api/video/generate', async (req, res) => {
  try {
    const { prompt, aspectRatio = '16:9', imageBase64, imageMimeType = 'image/png' } = req.body;
    const ai = getGeminiClient();

    const validAspectRatio = aspectRatio === '9:16' ? '9:16' : '16:9';

    let operation;
    if (imageBase64) {
      // Image to video
      operation = await ai.models.generateVideos({
        model: 'veo-3.1-fast-generate-preview',
        prompt: prompt || 'Animate this literary illustration into a gentle cinematic scene with subtle wind and glowing embers',
        image: {
          imageBytes: imageBase64,
          mimeType: imageMimeType,
        },
        config: {
          numberOfVideos: 1,
          resolution: '720p',
          aspectRatio: validAspectRatio,
        },
      });
    } else {
      // Text to video
      if (!prompt) {
        return res.status(400).json({ error: 'Prompt is required for text-to-video' });
      }
      operation = await ai.models.generateVideos({
        model: 'veo-3.1-fast-generate-preview',
        prompt,
        config: {
          numberOfVideos: 1,
          resolution: '720p',
          aspectRatio: validAspectRatio,
        },
      });
    }

    res.json({ operationName: operation.name });
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Failed to start video generation');
    console.error('Veo video generate error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

app.post('/api/video/status', async (req, res) => {
  try {
    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: 'operationName is required' });
    }

    const ai = getGeminiClient();
    const op = new GenerateVideosOperation();
    op.name = operationName;

    const updated = await ai.operations.getVideosOperation({ operation: op });
    res.json({
      done: updated.done || false,
      error: updated.error || null,
    });
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Failed to poll video status');
    console.error('Veo video status error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

app.post('/api/video/download', async (req, res) => {
  try {
    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: 'operationName is required' });
    }

    const ai = getGeminiClient();
    const op = new GenerateVideosOperation();
    op.name = operationName;

    const updated = await ai.operations.getVideosOperation({ operation: op });
    const uri = updated.response?.generatedVideos?.[0]?.video?.uri;

    if (!uri) {
      return res.status(404).json({ error: 'Video URI not found or generation failed' });
    }

    const apiKey = process.env.GEMINI_API_KEY || '';
    const videoRes = await fetch(uri, {
      headers: { 'x-goog-api-key': apiKey },
    });

    if (!videoRes.ok) {
      return res.status(videoRes.status).json({ error: 'Failed to download video file' });
    }

    res.setHeader('Content-Type', 'video/mp4');
    const arrayBuffer = await videoRes.arrayBuffer();
    res.send(Buffer.from(arrayBuffer));
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Failed to download video');
    console.error('Veo video download error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

