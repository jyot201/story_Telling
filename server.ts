// Helper: Gemini Client with required User-Agent
function getGeminiClient() {
  const apiKey = process.env.GEMINI_API_KEY;
  return new GoogleGenAI({
    apiKey: apiKey || '',
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

function formatGeminiError(error: any, fallbackMessage: string = 'Operation failed') {
  const msg = error?.message || (typeof error === 'object' ? JSON.stringify(error) : String(error));
  const isQuota =
    msg.includes('429') ||
    msg.includes('RESOURCE_EXHAUSTED') ||
    msg.includes('quota') ||
    msg.includes('rate-limits');

  if (isQuota) {
    return {
      status: 429,
      error: 'Gemini API quota exceeded. Veo 3 video generation and paid multimodal models require an active quota or billing plan on your Gemini API key (https://ai.google.dev/gemini-api/docs/rate-limits).',
      isQuota: true,
      originalMessage: msg,
    };
  }

  return {
    status: 500,
    error: msg || fallbackMessage,
    isQuota: false,
    originalMessage: msg,
  };
}

