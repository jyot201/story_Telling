// 2. Image Creation & Editing (gemini-3.1-flash-image-preview)
// -------------------------------------------------------------
app.post('/api/images/generate', async (req, res) => {
  try {
    const {
      prompt,
      aspectRatio = '16:9',
      imageSize = '1K',
      baseImageBase64,
      baseImageMimeType = 'image/png'
    } = req.body;

    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const ai = getGeminiClient();

    let parts: any[] = [];
    if (baseImageBase64) {
      // Editing existing image
      parts.push({
        inlineData: {
          data: baseImageBase64,
          mimeType: baseImageMimeType
        }
      });
      parts.push({ text: prompt });
    } else {
      // New image generation
      parts.push({ text: prompt });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.1-flash-image-preview',
      contents: { parts },
      config: {
        imageConfig: {
          aspectRatio: aspectRatio as any,
          imageSize: imageSize as any,
        }
      }
    });

    let imageUrl = '';
    let textDescription = '';

    const candidateParts = response.candidates?.[0]?.content?.parts || [];
    for (const part of candidateParts) {
      if (part.inlineData?.data) {
        const mime = part.inlineData.mimeType || 'image/png';
        imageUrl = `data:${mime};base64,${part.inlineData.data}`;
      } else if (part.text) {
        textDescription += part.text;
      }
    }

    if (!imageUrl) {
      return res.status(500).json({ error: 'Model did not return an image', text: textDescription });
    }

    res.json({ imageUrl, textDescription });
  } catch (error: any) {
    const formatted = formatGeminiError(error, 'Image generation failed');
    console.error('Image generation/edit error:', formatted.error);
    res.status(formatted.status).json(formatted);
  }
});

